"""Document names for the ten Eighth Schedule languages that had no entry in
`title_translations.py` -- Assamese, Bodo, Dogri, Kashmiri, Konkani, Maithili,
Manipuri, Nepali, Sanskrit and Santali.

WHY A SEPARATE MODULE, AND A WARNING ABOUT IT
---------------------------------------------
`localized_title`'s docstring records the rule the existing tables were built
under: "a title is only translated when a reliable translation exists, never
fabricated." The names below do NOT meet that bar, and are deliberately kept
out of `title_translations.py` so the distinction stays visible:

    PROVENANCE: machine-produced, NOT reviewed by native speakers.

These are legal document names, so a wrong term is not cosmetic -- it can
mislead someone about what they are filing. Confidence varies sharply by
language: Nepali, Assamese, Sanskrit, Maithili and Konkani are well-resourced
and the renderings below are likely sound; Bodo, Dogri, Manipuri, Santali and
Kashmiri are low-resource and should be treated as placeholders pending review.

Nothing here is load-bearing for correctness. These names are used only to
(a) recognize which template a user means and (b) display that name in chat.
The document CONTENT is generated by the LLM in the user's language and never
comes from this table, so a wrong entry degrades recognition -- it cannot put
wrong words into anyone's legal document. Deleting a language block simply
reverts that language to showing the English name.

Structured per-language for review convenience: a reviewer fluent in one
language reads one block. `NAMES_BY_DRAFT_ID` at the bottom inverts it into the
`{draft_id: {language: name}}` shape `title_translations.py` looks up.
"""

