def msg(key: str, language: str, default: str, **kwargs: str) -> str:
    """The localized wrapper sentence for `key` in `language`, with any
    `{placeholder}` filled from `kwargs`.

    `default` is the original English wording (passed in by the caller,
    which already has it inline) -- used whenever `language` isn't covered
    for that `key`. Never raises, never returns a blank string.
    """
    template = _MESSAGES.get(key, {}).get(language, default)
    return template.format(**kwargs) if kwargs else template
