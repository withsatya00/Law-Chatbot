"""Formal scaffolding paragraphs for the deterministic (non-LLM) draft path.

Why this module exists
----------------------
Two real drafts, generated by this app, side by side:

* An English **Mobile Theft Complaint** -- three pages, with a proper opening
  submission, a numbered statement of facts followed by a reading-instruction
  paragraph, a four-paragraph hedged Legal Position, a Consequences section,
  an enumerated Prayer with six procedural requests, and a Verification.
  It reads like something an advocate's office produced.

* A Hindi **धन वसूली नोटिस** (Recovery Notice) -- two pages, in which
  "कानूनी स्थिति" is a single sentence, "परिणाम" is one line, and the entire
  "प्रार्थना" section reads "उपलब्ध नहीं कराया गया।" It reads like a form
  someone half-filled.

Both came out of the same deterministic builder. The difference was one
condition in `LegalDraftEngine._deterministic_complaint_sections`::

    if template.category == "Complaint" and language in {"english", "hinglish"}:

The Hindi recovery notice failed *both* halves -- wrong category and wrong
language -- so it received none of the scaffolding, and every non-English user
and every non-Complaint document got a visibly second-class draft.

What this module changes, and what it deliberately does not
-----------------------------------------------------------
It supplies that scaffolding per **category** (a notice to a private party
must not talk about "the receiving authority", and a complaint must not
"reserve the right to initiate proceedings") and per **language**.

The original code's instinct was right and is kept: a Hindi document must
never be padded with English paragraphs. So scaffolding is applied only for
languages it has actually been authored in (`supports_scaffolding`), and any
other language keeps its concise localized fallback rather than a
mixed-language document. Adding a language here is purely additive.

Nothing here is generated, and nothing here asserts a fact. Every paragraph is
procedural or hedging -- it adds no event, person, date, amount, document,
loss or allegation. The user's own narrative remains the sole factual account
of the matter, exactly as before.

TRANSLATION PROVENANCE: the English text is carried over verbatim from the
paragraphs previously inlined in `engine.py`. The Hindi is authored here in
standard legal-drafting register. Like the rest of this codebase's
translations it has NOT been reviewed by a practising advocate, and should be
before this is relied on in production.
"""

from __future__ import annotations

# Languages with authored scaffolding. A language outside this set keeps the
# short localized fallback -- never a document with English paragraphs bolted
# onto Hindi/Tamil/Bengali prose. "hinglish" shares the English text by
# design: a Hinglish draft is written in Latin script with English legal
# terminology, so the English formal register is the correct one for it.
SCAFFOLDED_LANGUAGES = frozenset({"english", "hinglish", "hindi"})

# Categories that receive scaffolding. Affidavit and Contract are excluded on
# purpose: an affidavit's force comes from its sworn verification clause and a
# contract's from its operative terms, so neither is improved -- and both are
# arguably weakened -- by added procedural narration.
SCAFFOLDED_CATEGORIES = frozenset({"Complaint", "Notice", "Application"})


def supports_scaffolding(language: str, category: str) -> bool:
    return language in SCAFFOLDED_LANGUAGES and category in SCAFFOLDED_CATEGORIES


