def apply_official_scaffolding(
    sections: dict[str, str], *, category: str, language: str
) -> dict[str, str]:
    """Append the formal paragraphs for `category` to `sections`, in place.

    A section that the deterministic builder did not produce at all is created
    only if the scaffolding for it is self-contained; sections whose
    scaffolding reads as a continuation ("The foregoing numbered statements
    ...") are skipped when there is nothing for them to continue, so a draft
    can never open a Facts section that has no facts in it.

    No-ops for any language/category outside `supports_scaffolding`, which is
    what keeps a Tamil or Bengali draft free of English paragraphs.
    """
    if not supports_scaffolding(language, category):
        return sections
    # "hinglish" is written in English legal register; share that text.
    text_language = "english" if language in ("english", "hinglish") else language
    # Sections whose scaffolding only makes sense appended to existing
    # content -- never used to create the section from nothing.
    continuation_only = {"Facts of the Case", "Consequences", "Legal Position"}
    for heading, translations in _SCAFFOLDING.get(category, {}).items():
        addition = translations.get(text_language)
        if not addition:
            continue
        existing = sections.get(heading, "").strip()
        if not existing and heading in continuation_only:
            continue
        sections[heading] = f"{existing}\n\n{addition}" if existing else addition
    return sections
