def phrase(key: str, language: str, default: str, **kwargs: str) -> str:
    """The localized boilerplate/label text for `key` in `language`, with any
    `{placeholder}` in the chosen template filled from `kwargs`.

    `default` is the original English wording (passed in by the caller,
    which already has it inline as the pre-Part-53 literal) -- used whenever
    `language` isn't covered for that `key` (english/hinglish, or any
    language outside the fixed set above). Never raises, never returns a
    blank string.
    """
    template = _PHRASES.get(key, {}).get(language, default)
    return template.format(**kwargs) if kwargs else template


