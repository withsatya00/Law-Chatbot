# verified document in the Knowledge Base" with no helplines, no steps, and
# no offer to draft anything. A Marathi user asking the same question got the
# same. The identical question in ENGLISH was matched and answered. The
# guardrail was working as designed; the guidance that is supposed to
# accompany it never fired, because these patterns covered English plus a few
# token Hindi phrases.
#
# Two concrete gaps, both fixed below:
#   * The Hindi cyber-fraud pattern required the literal "खाते से पैसे".
#     "खाते से बिना अनुमति ... निकल गए" -- the natural way to say it -- has
#     other words between "खाते से" and any money noun, so it never matched.
#   * Marathi, Gujarati, Tamil, Telugu, Kannada, Bengali, Punjabi, Malayalam,
#     Odia and Urdu had no cyber-fraud vocabulary at all.
#
# The verbs matter more than the nouns here: people describe this as money
# having "gone"/"been taken"/"been cut" far more often than they name a
# category like "fraud" or "cyber". Ordered most-urgent-first: a message about
# being threatened AND defrauded should surface the personal-safety channel,
# not just the money one.
