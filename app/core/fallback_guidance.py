"""Part 58 "Answer Quality Audit" issues 16 & 23: making the strict-RAG
refusal actionable.

`NO_VERIFIED_CONTEXT_MESSAGES` is a hard guardrail -- when nothing in the
knowledge base clears the relevance gate, the system must not answer from
pre-trained knowledge. That part stays exactly as it is. What was wrong was
what the user was left with: someone typing "a man keeps phoning me,
harassing and threatening me -- how do I write a police complaint?" got a
bare "no verified document in the Knowledge Base" and nothing else. For an
urgent safety situation that is a failure of the product, not a display of
rigour.

This module supplies the missing half WITHOUT weakening the guardrail. It
adds no legal analysis, no statutory interpretation, and no claim about what
the law says -- only:

* Government of India emergency/reporting channels, which are published
  public-service numbers, cited by name so the user can verify them.
* Generic, jurisdiction-independent practical steps (preserve evidence,
  approach the police station, escalate to the Superintendent of Police,
  consult an advocate) that are true regardless of which provision applies.
* A pointer to a document this app can actually draft, when the question
  maps to one.

Everything here is a fixed, reviewed string. Nothing is generated by the LLM,
so nothing can be hallucinated into it.
"""

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class GuidanceCategory:
    key: str
    pattern: re.Pattern[str]
    # Draft template to offer, when this app has one for the situation.
    draft_id: str | None


