def generic_next_steps_guidance(language: str | None) -> str:
    """The non-urgent counterpart to `actionable_guidance`: concrete next
    steps for an ORDINARY informational question that found no verified
    source, as opposed to a safety situation. Never returns "" -- unlike
    `actionable_guidance`, there is no "this doesn't need guidance" case
    here; every strict-RAG refusal that isn't already covered by an urgency
    category reaches this instead (see `_no_verified_context_answer`)."""
    resolved = (language or "english").strip().lower()
    if resolved not in _GENERIC_NEXT_STEPS:
        # Heading and steps must come from the SAME language: a language in
        # `_HEADINGS` but not here would otherwise get a native heading over
        # English steps.
        resolved = "english"
    steps = _GENERIC_NEXT_STEPS[resolved]
    lines = [f"**{_localized(_HEADINGS, resolved)}**", ""]
    lines.extend(f"{index}. {step}" for index, step in enumerate(steps, start=1))
    return "\n".join(lines)


def actionable_guidance(
    question: str, language: str | None, template_name: str | None = None, template_command: str | None = None
) -> str:
    """The block appended to a strict-RAG refusal, or `""` when the question
    isn't one where a bare refusal leaves the user stranded.

    `template_name` is the already-localized display name of a draft this app
    can produce for the situation, and `template_command` its English name
    (what the user should actually type); the caller resolves both, since this
    module has no business importing the drafting package.
    """
    category = detect_category(question)
    if category is None:
        return ""
    resolved = (language or "english").strip().lower()
    if resolved not in _STEPS:
        # Languages that only have the generic-guidance tables (see
        # `_GENERIC_NEXT_STEPS`) get the WHOLE urgent block in English rather
        # than a native heading over English steps.
        resolved = "english"
    # `_STEPS`, `_HEADINGS`, `_CHANNEL_LABELS`, `_SOURCE_NOTES` and (since the
    # BUG-01/BUG-02 fix) `_DRAFT_OFFERS` all cover the identical 13-language
    # set deliberately -- every line of this block must resolve together, or
    # a language in one table but not another produces a same-block script
    # mix instead of a clean single-language fallback. A language outside all
    # of them falls back to English steps rather than showing nothing.
    steps = _STEPS.get(resolved, _STEPS["english"]).get(category.key) or _STEPS["english"][category.key]
    lines = [
        f"**{_localized(_HEADINGS, resolved)}**",
        "",
        f"*{_localized(_CHANNEL_LABELS, resolved)}:* " + " · ".join(_CHANNELS[category.key]),
        "",
    ]
    lines.extend(f"{index}. {step}" for index, step in enumerate(steps, start=1))
    if template_name:
        lines.append("")
        lines.append(
            _localized(_DRAFT_OFFERS, resolved).format(
                template=template_name, command=template_command or template_name
            )
        )
    lines.append("")
    lines.append(f"> {_localized(_SOURCE_NOTES, resolved)}")
    return "\n".join(lines)
