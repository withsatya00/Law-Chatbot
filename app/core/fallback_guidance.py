def detect_category(question: str) -> GuidanceCategory | None:
    """The urgency category `question` falls into, or `None` for an ordinary
    informational question that needs no safety escalation."""
    for category in _CATEGORIES:
        if category.pattern.search(question or ""):
            return category
    return None


